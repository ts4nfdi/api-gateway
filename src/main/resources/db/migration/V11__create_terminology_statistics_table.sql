-- Statistics per terminology. Rows are written only by the external
-- statistics script; the API Gateway only reads them.
-- Terminologies live outside this database, thus this standalone table.
CREATE TABLE IF NOT EXISTS terminology_statistics
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uri                    VARCHAR(255) NOT NULL,
    source                 VARCHAR(255) NOT NULL,
    timestamp              TIMESTAMP    NOT NULL,
    property_count         BIGINT       NOT NULL DEFAULT 0,
    class_count            BIGINT       NOT NULL DEFAULT 0,
    named_individual_count BIGINT       NOT NULL DEFAULT 0,
    concept_count          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_terminology_statistics PRIMARY KEY (id)
    );

CREATE INDEX IF NOT EXISTS idx_terminology_statistics_uri_source
    ON terminology_statistics (uri, source, timestamp DESC);