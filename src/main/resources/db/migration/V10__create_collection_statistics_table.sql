-- Statistics per terminology collection. Rows are written only by the external
-- statistics script; the API Gateway only reads them.
CREATE TABLE IF NOT EXISTS collection_statistics
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    collection_id          UUID      NOT NULL,
    "timestamp"            TIMESTAMP NOT NULL,
    property_count         BIGINT    NOT NULL DEFAULT 0,
    class_count            BIGINT    NOT NULL DEFAULT 0,
    named_individual_count BIGINT    NOT NULL DEFAULT 0,
    concept_count          BIGINT    NOT NULL DEFAULT 0,
    CONSTRAINT pk_collection_statistics PRIMARY KEY (id),
    CONSTRAINT fk_collection_statistics_on_collection FOREIGN KEY (collection_id)
    REFERENCES terminology_collection (id) ON DELETE CASCADE
    );

CREATE INDEX IF NOT EXISTS idx_collection_statistics_collection_id
    ON collection_statistics (collection_id);